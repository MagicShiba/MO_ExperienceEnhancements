#!/usr/bin/env python3
# mkicons.py - src/icon_*.png -> src/icons.inc (build-time, stdlib only).
#
#约定 (与底部闪电点阵一致): 黑=墨, 白=忽略。转换取覆盖率 = 255-亮度
# (灰度天然抗锯齿)。RGBA 先压到白底再转亮度。
# 接受: 8bit RGB/RGBA/灰度, 非交错, 边长<=32。宽度归一化 (居中补白透明),
# 步进统一 = 归一宽度, 对齐天然成立。
# 用法: py icons/mkicons.py   (构建.bat 自动调; 缺文件/格式不对即报错退出)
# 输出: src/icons.inc (确定性字节, 同输入同输出, 勿手改)

import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = [
    ("icon_power_up.png", "PWR_UP"),
    ("icon_power_down.png", "PWR_DOWN"),
    ("icon_time.png", "TIME"),
    ("icon_cost.png", "COST"),
]
OUT = os.path.join(HERE, "..", "src", "icons.inc")
MAXSIDE = 32


def fail(msg):
    sys.stderr.write("mkicons: error: " + msg + "\n")
    sys.exit(1)


def read_png(path):
    d = open(path, "rb").read()
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        fail(path + ": not a PNG file")
    pos = 8
    w = h = bd = ct = None
    inter = None
    idat = b""
    while pos + 8 <= len(d):
        (ln,) = struct.unpack(">I", d[pos:pos + 4])
        typ = d[pos + 4:pos + 8]
        body = d[pos + 8:pos + 8 + ln]
        if len(body) != ln:
            fail(path + ": truncated chunk")
        if typ == b"IHDR":
            (w, h, bd, ct, comp, filt, inter) = struct.unpack(">IIBBBBB", body)
            if bd != 8:
                fail(path + ": only 8-bit PNG supported")
            if ct not in (0, 2, 6):
                fail(path + ": only gray/RGB/RGBA supported")
            if inter != 0:
                fail(path + ": interlaced PNG not supported, re-save as non-interlaced")
        elif typ == b"IDAT":
            idat += body
        elif typ == b"IEND":
            break
        pos += 12 + ln
    if w is None:
        fail(path + ": missing IHDR")
    if w < 1 or h < 1 or w > MAXSIDE or h > MAXSIDE:
        fail(path + ": size %dx%d out of range (1..%d)" % (w, h, MAXSIDE))
    raw = zlib.decompress(idat)
    ch = {0: 1, 2: 3, 6: 4}[ct]
    stride = w * ch
    px = []
    prev = bytearray(stride)
    p = 0
    for yy in range(h):
        f = raw[p]
        p += 1
        cur = bytearray(raw[p:p + stride])
        p += stride
        if f == 1:
            for i in range(ch, stride):
                cur[i] = (cur[i] + cur[i - ch]) & 255
        elif f == 2:
            for i in range(stride):
                cur[i] = (cur[i] + prev[i]) & 255
        elif f == 3:
            for i in range(stride):
                a = cur[i - ch] if i >= ch else 0
                cur[i] = (cur[i] + ((a + prev[i]) >> 1)) & 255
        elif f == 4:
            for i in range(stride):
                a = cur[i - ch] if i >= ch else 0
                b = prev[i]
                c = prev[i - ch] if i >= ch else 0
                pp = a + b - c
                pa, pb, pc = abs(pp - a), abs(pp - b), abs(pp - c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                cur[i] = (cur[i] + pr) & 255
        elif f != 0:
            fail(path + ": bad filter %d" % f)
        prev = cur
        row = []
        for xx in range(w):
            if ct == 6:
                r, g, b, a = cur[xx * 4], cur[xx * 4 + 1], cur[xx * 4 + 2], cur[xx * 4 + 3]
                r = (r * a + 255 * (255 - a)) // 255
                g = (g * a + 255 * (255 - a)) // 255
                b = (b * a + 255 * (255 - a)) // 255
            elif ct == 2:
                r, g, b = cur[xx * 3], cur[xx * 3 + 1], cur[xx * 3 + 2]
            else:
                r = g = b = cur[xx]
            lum = (r * 299 + g * 587 + b * 114) // 1000
            row.append(255 - lum)
        px.append(row)
    return w, h, px


def main():
    icons = []
    for name, tag in FILES:
        path = os.path.join(HERE, name)
        if not os.path.isfile(path):
            fail("missing " + path)
        w, h, px = read_png(path)
        icons.append((tag, w, h, px))
        print("mkicons: %s %dx%d" % (name, w, h))
    W = max(w for _, w, _, _ in icons)
    HMAX = max(h for _, _, h, _ in icons)
    out = []
    out.append("/* auto-generated by src/mkicons.py from src/icon_*.png - do not edit */")
    out.append("#define ICON_N %d" % len(icons))
    out.append("#define ICON_W %d" % W)
    out.append("#define ICON_HMAX %d" % HMAX)
    out.append("static const int g_IconW[ICON_N] = {%s};" % ",".join(str(w) for _, w, _, _ in icons))
    out.append("static const int g_IconH[ICON_N] = {%s};" % ",".join(str(h) for _, _, h, _ in icons))
    out.append("static const unsigned char g_IconPx[ICON_N][ICON_W*ICON_HMAX] = {")
    for tag, w, h, px in icons:
        out.append("/* %s %dx%d, coverage=255-luma, stride=ICON_W */" % (tag, w, h))
        out.append("{")
        pad = (W - w) // 2
        for yy in range(HMAX):
            if yy < h:
                row = [0] * pad + px[yy] + [0] * (W - pad - w)
            else:
                row = [0] * W
            out.append(",".join(str(v) for v in row) + ",")
        out.append("},")
    out.append("};")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("mkicons: wrote %s (W=%d HMAX=%d)" % (OUT, W, HMAX))


main()
