#!/usr/bin/env python3
# mkicons.py - icons/icon_*.png -> icons/icons.inc + icons/mapicons.inc (手动跑, stdlib only).
#
# 两类输出 (互不相干, 分属两个运行时模块):
#  1) 字形图标 GLYPHS: 提示栏文字里画的 PUA 小图 (▲▼○ 等)。约定黑=墨白=忽略,
#     覆盖率 = 255-亮度 (灰度天然抗锯齿), RGBA 先压到白底; 运行期由调用方给墨色。
#     输出 icons.inc (g_IconPx 等), 对应 Icon.cpp。
#  2) 地图图像 IMAGES: 独立绘制 (不进文字) 的彩色图 (icon_aggressive)。保留原图
#     RGBA, 运行期按像素本色混合。输出 mapicons.inc (g_MapIconRGBA), 对应 IconMap.cpp。
#
# 接受: 8bit RGB/RGBA/灰度, 非交错, 边长<=32。字形宽度归一化 (居中补白, 等宽对齐)。
# 构建 .bat 平时不调本脚本, 改图后手动跑一次。用法: py icons/mkicons.py

import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))

# (文件名, 标签) - 文字内绘制的字形图标 (单色, 墨色由调用方定)
GLYPHS = [
    ("icon_power_up.png", "PWR_UP"),
    ("icon_power_down.png", "PWR_DOWN"),
    ("icon_time.png", "TIME"),
    ("icon_cost.png", "COST"),
]
# (文件名, 标签) - 独立地图图像 (彩色, 原图 RGBA; 槽位宏见 IconMap.h)
IMAGES = [
    ("icon_aggressive.png", "AGGRESSIVE"),
]

OUT = os.path.join(HERE, "icons.inc")
OUT_IMG = os.path.join(HERE, "mapicons.inc")
MAXSIDE = 32


def fail(msg):
    sys.stderr.write("mkicons: error: " + msg + "\n")
    sys.exit(1)


def read_png(path):
    """-> (w, h, rows); rows[yy][xx] = (r, g, b, a)。a=255 若无 alpha 通道, 不做预乘。"""
    d = open(path, "rb").read()
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        fail(path + ": not a PNG file")
    pos = 8
    w = h = bd = ct = None
    inter = None
    idat = b""
    while pos + 8 <= len(d):
        (ln,) = struct.unpack(">I", d[pos:pos + 4])
        typ = d[pos + 4:pos + 8]
        body = d[pos + 8:pos + 8 + ln]
        if len(body) != ln:
            fail(path + ": truncated chunk")
        if typ == b"IHDR":
            (w, h, bd, ct, comp, filt, inter) = struct.unpack(">IIBBBBB", body)
            if bd != 8:
                fail(path + ": only 8-bit PNG supported")
            if ct not in (0, 2, 6):
                fail(path + ": only gray/RGB/RGBA supported")
            if inter != 0:
                fail(path + ": interlaced PNG not supported, re-save as non-interlaced")
        elif typ == b"IDAT":
            idat += body
        elif typ == b"IEND":
            break
        pos += 12 + ln
    if w is None:
        fail(path + ": missing IHDR")
    if w < 1 or h < 1 or w > MAXSIDE or h > MAXSIDE:
        fail(path + ": size %dx%d out of range (1..%d)" % (w, h, MAXSIDE))
    raw = zlib.decompress(idat)
    ch = {0: 1, 2: 3, 6: 4}[ct]
    stride = w * ch
    rows = []
    prev = bytearray(stride)
    p = 0
    for yy in range(h):
        f = raw[p]
        p += 1
        cur = bytearray(raw[p:p + stride])
        p += stride
        if f == 1:
            for i in range(ch, stride):
                cur[i] = (cur[i] + cur[i - ch]) & 255
        elif f == 2:
            for i in range(stride):
                cur[i] = (cur[i] + prev[i]) & 255
        elif f == 3:
            for i in range(stride):
                a = cur[i - ch] if i >= ch else 0
                cur[i] = (cur[i] + ((a + prev[i]) >> 1)) & 255
        elif f == 4:
            for i in range(stride):
                a = cur[i - ch] if i >= ch else 0
                b = prev[i]
                c = prev[i - ch] if i >= ch else 0
                pp = a + b - c
                pa, pb, pc = abs(pp - a), abs(pp - b), abs(pp - c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                cur[i] = (cur[i] + pr) & 255
        elif f != 0:
            fail(path + ": bad filter %d" % f)
        prev = cur
        row = []
        for xx in range(w):
            if ct == 6:
                r, g, b, a = cur[xx * 4], cur[xx * 4 + 1], cur[xx * 4 + 2], cur[xx * 4 + 3]
            elif ct == 2:
                r, g, b = cur[xx * 3], cur[xx * 3 + 1], cur[xx * 3 + 2]
                a = 255
            else:
                r = g = b = cur[xx]
                a = 255
            row.append((r, g, b, a))
        rows.append(row)
    return w, h, rows


def to_coverage(r, g, b, a):
    """压到白底再转亮度, 覆盖率 = 255-亮度 (灰度天然抗锯齿)。"""
    r = (r * a + 255 * (255 - a)) // 255
    g = (g * a + 255 * (255 - a)) // 255
    b = (b * a + 255 * (255 - a)) // 255
    return 255 - (r * 299 + g * 587 + b * 114) // 1000


def read_or_fail(name):
    path = os.path.join(HERE, name)
    if not os.path.isfile(path):
        fail("missing " + path)
    return read_png(path)


def gen_glyphs():
    icons = []
    for name, tag in GLYPHS:
        w, h, rows = read_or_fail(name)
        px = [[to_coverage(*p) for p in row] for row in rows]
        icons.append((tag, w, h, px))
        print("mkicons: %s %dx%d (glyph)" % (name, w, h))
    W = max(w for _, w, _, _ in icons)
    HMAX = max(h for _, _, h, _ in icons)
    out = []
    out.append("/* auto-generated by icons/mkicons.py from icons/icon_*.png - do not edit */")
    out.append("#define ICON_N %d" % len(icons))
    out.append("#define ICON_W %d" % W)
    out.append("#define ICON_HMAX %d" % HMAX)
    out.append("static const int g_IconW[ICON_N] = {%s};" % ",".join(str(w) for _, w, _, _ in icons))
    out.append("static const int g_IconH[ICON_N] = {%s};" % ",".join(str(h) for _, _, h, _ in icons))
    out.append("static const unsigned char g_IconPx[ICON_N][ICON_W*ICON_HMAX] = {")
    for tag, w, h, px in icons:
        out.append("/* %s %dx%d, coverage=255-luma, stride=ICON_W */" % (tag, w, h))
        out.append("{")
        pad = (W - w) // 2
        for yy in range(HMAX):
            row = ([0] * pad + px[yy] + [0] * (W - pad - w)) if yy < h else [0] * W
            out.append(",".join(str(v) for v in row) + ",")
        out.append("},")
    out.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("mkicons: wrote %s (W=%d HMAX=%d)" % (OUT, W, HMAX))


def gen_images():
    imgs = []
    for name, tag in IMAGES:
        w, h, rows = read_or_fail(name)
        imgs.append((tag, w, h, rows))
        print("mkicons: %s %dx%d (image)" % (name, w, h))
    pixmax = max(w * h for _, w, h, _ in imgs)
    out = []
    out.append("/* auto-generated by icons/mkicons.py from icons/icon_*.png - do not edit */")
    out.append("/* 独立地图图像 (彩色, 原图 RGBA)。槽位宏见 IconMap.h (MAPICON_*)。 */")
    out.append("#define MAPICON_N %d" % len(imgs))
    out.append("#define MAPICON_PIXMAX %d" % pixmax)
    out.append("static const int g_MapIconW[MAPICON_N] = {%s};" % ",".join(str(w) for _, w, _, _ in imgs))
    out.append("static const int g_MapIconH[MAPICON_N] = {%s};" % ",".join(str(h) for _, _, h, _ in imgs))
    out.append("/* 每像素 4 字节 R,G,B,A (行宽 = g_MapIconW, 无补白) */")
    out.append("static const unsigned char g_MapIconRGBA[MAPICON_N][MAPICON_PIXMAX*4] = {")
    for tag, w, h, rows in imgs:
        out.append("/* %s %dx%d */" % (tag, w, h))
        out.append("{")
        vals = []
        for yy in range(h):
            for xx in range(w):
                vals += list(rows[yy][xx])
        vals += [0] * ((pixmax - w * h) * 4)
        for i in range(0, len(vals), 16):
            out.append(",".join(str(v) for v in vals[i:i + 16]) + ",")
        out.append("},")
    out.append("};")
    with open(OUT_IMG, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("mkicons: wrote %s (PIXMAX=%d)" % (OUT_IMG, pixmax))


def main():
    gen_glyphs()
    gen_images()


main()
