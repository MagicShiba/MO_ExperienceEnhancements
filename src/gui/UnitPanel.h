/* UnitPanel.h - 画面左下角的选中信息面板 + 左侧竖排按钮列。
 *
 * 版式: 九宫格外框 (border_mental_n9_B.pcx) 只包格子, 格数按内容定 (单选 2 格,
 * 4 架 2x2, 9 个以上才 3x3); 框外左侧一列自下而上的按钮 (折叠 / 操作模式 /
 * 收藏槽)。没选中东西时整块框不显示。
 *   - 单选: 第 0 格图标 (等级/弹药), 第 1 格血量 + 经验, 第 2 格起是本车/本建筑
 *     的载员 (超过 7 个翻页, 前两格每页固定, 末页末格是"更多")。
 *   - 敌方单位: 只画图标 + 血量。
 *   - 同型多选: 每单位一格, 空弹优先排前。
 *   - 混型: <=9 个全展开; >9 按类型分组, 右上角画数量。
 * 点格子 = 选中那个单位 (组则整组)。有载员时点载员格 = 单个下车, 按住 Z 点 =
 * 给该载员规划路径点 (见 SingleUnload.h)。
 *
 * 绘制落点: Composite, 每帧由消息帧钩调用。只读模拟状态 + 只改本机选中集, 联机安全。
 * 键盘移动的键位/连按规则见 notes/键盘移动.md。 */
#pragma once

/* 读 [UnitPanel] 配置 (幂等)。 */
void UP_EnsureInit(void);

/* 每循环 (prepare 钩): 快照选中集 / 摆位 / 取点击 / 悬停。 */
void UP_Poll(void);

/* 画进 Composite。返回 1 = 画过。 */
int UP_Draw(void);

/* 滚轮落在面板上则翻页 (dir: 1=下, -1=上)。返回 1 = 已吃掉。 */
int UP_WheelIn(int mx, int my, int dir);
